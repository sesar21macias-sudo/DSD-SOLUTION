export const dicts: Record<Lang, Dict> = { es, en };

export type ErrorKey = keyof Dict["errors"];

export function isLang(v: unknown): v is Lang {
  return v === "es" || v === "en";
}

/** Primer idioma soportado en Accept-Language; español si no hay ninguno. */
export function langFromHeader(h: string | null | undefined): Lang {
  if (!h) return "es";
  for (const part of h.split(",")) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return "es";
}

export function errorText(lang: Lang, key: ErrorKey, args: unknown[] = []): string {
  const m = dicts[lang].errors[key] as string | ((...a: unknown[]) => string);
  return typeof m === "function" ? m(...args) : m;
}
